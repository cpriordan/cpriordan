def _normalize_url(u: str) -> str:
    if not u:
        return u
    if u.startswith('//'):
        u = 'https:' + u
    parts = urlsplit(u)
    parts = parts._replace(query='', fragment='')
    return urlunsplit(parts)


async def get_hero_background_img_url(page) -> Optional[str]:
    """
    Get the hero background image URL.
    Handles both standard hero structure and Finalytics ad overlay.
    
    Three strategies:
    1. Standard .hero__background img (normal hero structure)
    2. Broader .hero img (Finalytics ad overlay)
    3. Find any large visible image (fallback)
    
    Returns None if not found.
    """
    # Strategy 1: Try standard hero structure first
    standard_selector = ".hero__background img"
    try:
        img = page.locator(standard_selector).first
        await img.wait_for(state="visible", timeout=3000)
        print("[Hero Image] Found in standard .hero__background structure")
        
        srcset = await img.get_attribute('srcset')
        if srcset:
            first = srcset.split(',')[0].strip().split(' ')[0]
            if first:
                return urljoin(page.url, first)
        
        src = await img.get_attribute('src')
        if src:
            return urljoin(page.url, src)
            
    except PlaywrightTimeoutError:
        print("[Hero Image] Not found in standard hero structure")
    except Exception as e:
        print(f"[Hero Image] Error with standard selector: {e}")
    
    # Strategy 2: Try broader hero selector (for Finalytics ad overlay)
    broader_selector = ".hero img"
    try:
        img = page.locator(broader_selector).first
        await img.wait_for(state="visible", timeout=3000)
        print("[Hero Image] Found using broader .hero img selector (likely Finalytics ad)")
        
        srcset = await img.get_attribute('srcset')
        if srcset:
            first = srcset.split(',')[0].strip().split(' ')[0]
            if first:
                return urljoin(page.url, first)
        
        src = await img.get_attribute('src')
        if src:
            return urljoin(page.url, src)
            
    except PlaywrightTimeoutError:
        print("[Hero Image] Not found with broader selector")
    except Exception as e:
        print(f"[Hero Image] Error with broader selector: {e}")
    
    # Strategy 3: Try to find any visible large image (fallback)
    try:
        all_images = await page.locator("img[src], img[srcset]").all()
        
        for img in all_images:
            try:
                is_visible = await img.is_visible()
                if not is_visible:
                    continue
                
                box = await img.bounding_box()
                if box and box['width'] > 300 and box['height'] > 200:
                    # This is likely a hero-sized image
                    print(f"[Hero Image] Found large visible image ({box['width']}x{box['height']})")
                    
                    srcset = await img.get_attribute('srcset')
                    if srcset:
                        first = srcset.split(',')[0].strip().split(' ')[0]
                        if first:
                            return urljoin(page.url, first)
                    
                    src = await img.get_attribute('src')
                    if src:
                        return urljoin(page.url, src)
                        
            except Exception:
                continue
                
    except Exception as e:
        print(f"[Hero Image] Error in fallback strategy: {e}")
    
    print("[Hero Image] Could not find hero image with any strategy")
    return None




