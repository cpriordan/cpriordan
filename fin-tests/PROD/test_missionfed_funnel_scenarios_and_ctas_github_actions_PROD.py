async def try_click_cookie_accept(page, screenshots_directory: Path):
    """
    Attempts to click cookie acceptance button with improved timing and verification.
    Waits for cookie banner to be fully loaded before attempting to click.
    """
    # First, wait a bit for cookie layer to potentially appear
    await page.wait_for_timeout(1500)
    
    # Take a screenshot before attempting cookie acceptance for debugging
    try:
        await page.screenshot(path=str(screenshots_directory / '0_before_cookie_accept.png'))
        print("Screenshot taken before cookie acceptance")
    except Exception as e:
        print(f"Could not take pre-cookie screenshot: {e}")
    
    for sel in COOKIE_ACCEPT_SELECTORS:
        locator = page.locator(sel)
        try:
            if await locator.count() > 0:
                # Wait for the button to be visible and stable
                await locator.first.wait_for(state="visible", timeout=3000)
                await locator.first.wait_for(state="attached", timeout=2000)
                # Additional wait for any animations
                await page.wait_for_timeout(500)
                try:
                    await locator.first.click()
                    print(f"Clicked cookie accept button via selector: {sel}")
                except Exception:
                    handle = await locator.first.element_handle()
                    if handle:
                        await page.evaluate('(el)=>el.click()', handle)
                        print(f"Clicked cookie accept via JS: {sel}")
                # Wait after click for cookie banner to disappear
                await asyncio.sleep(1.0)
        except Exception as e:
            print(f"Exception while trying cookie selector {sel}: {e}")
            continue

    banner_still_present = False
    for cont in COOKIE_BANNER_CONTAINERS:
        try:
            count = await page.locator(cont).count()
            if count > 0:
                for i in range(count):
                    if await page.locator(cont).nth(i).is_visible():
                        banner_still_present = True
                        print(f"Cookie banner container still visible: {cont}")
                        break
        except Exception:
            pass

    if banner_still_present:
        try:
            await page.screenshot(path=str(screenshots_directory / '10_cookie_layer_might_be_still_blocking.png'))
        except Exception:
            pass
        css_rules = ','.join(COOKIE_BANNER_CONTAINERS) + '{ display:none !important; visibility:hidden !important; }'
        await page.add_style_tag(content=css_rules)
        print("Injected CSS to hide persistent cookie banner in test context.")
        await asyncio.sleep(0.25)
    return True


